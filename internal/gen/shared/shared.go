// Package shared holds the parts of request generation that do not depend on the
// language being generated: how a comment is wrapped, the prose the generated
// documentation is written in, which properties a record type holds, and how a
// name is kept unique.
package shared

import (
	"io"
	"path"
	"slices"
	"strconv"
	"strings"

	"github.com/linyows/jmapc/internal/request"
	"github.com/linyows/jmapc/internal/spec"
)

// GeneratedBanner is the first line of every file jmapc writes. It marks the
// file as generated for the tools that read one, and it is how jmapc tells its
// own output apart from a file put in the same directory by hand.
const GeneratedBanner = "// Code generated by jmapc. DO NOT EDIT."

// commentWidth is the column the generated comments wrap at, counting the
// indent and the "// " prefix.
const commentWidth = 78

// WriteComment writes text as a comment, wrapped to commentWidth and prefixed
// with the given indent. Go and TypeScript spell a comment the same way, so one
// implementation serves both. It writes nothing for empty text.
func WriteComment(w io.Writer, indent, text string) {
	WriteCommentMarker(w, indent, "//", text)
}

// WriteCommentMarker is WriteComment for a language that spells a comment with
// something other than "//". Rust documents an item with "///", and wants the
// text wrapped to the same column all the same.
func WriteCommentMarker(w io.Writer, indent, marker, text string) {
	for _, line := range wrapComment(indent, marker, text) {
		io.WriteString(w, line)
		io.WriteString(w, "\n")
	}
}

// wrapComment returns the comment lines for text, each already carrying its
// indent and comment marker.
func wrapComment(indent, marker, text string) []string {
	text = strings.TrimSpace(text)
	if text == "" {
		return nil
	}
	limit := commentWidth - len(indent) - len(marker) - 1
	if limit < 20 {
		limit = 20
	}
	var lines []string
	for _, para := range strings.Split(text, "\n") {
		para = strings.TrimSpace(para)
		if para == "" {
			lines = append(lines, indent+marker)
			continue
		}
		var cur strings.Builder
		for _, word := range strings.Fields(para) {
			switch {
			case cur.Len() == 0:
				cur.WriteString(word)
			case cur.Len()+1+len(word) <= limit:
				cur.WriteByte(' ')
				cur.WriteString(word)
			default:
				lines = append(lines, indent+marker+" "+cur.String())
				cur.Reset()
				cur.WriteString(word)
			}
		}
		if cur.Len() > 0 {
			lines = append(lines, indent+marker+" "+cur.String())
		}
	}
	return lines
}

// Unique returns name, or name with a number appended, so that nothing in
// taken already has it. It records what it returns, so the next caller sees the
// name as taken.
func Unique(taken map[string]bool, name string) string {
	candidate := name
	for i := 2; taken[candidate]; i++ {
		candidate = name + strconv.Itoa(i)
	}
	taken[candidate] = true
	return candidate
}

// RecordProperties returns the properties a record type of dataType holds.
// Where withID says the method returns the id whatever it is asked for, as a
// /get does, the id is among them whether or not the request asked for it. A
// property that comes back as fields of other names, as the data of a blob
// does, is held as those fields, each once.
func RecordProperties(dataType *spec.Object, props []string, withID bool) []string {
	out := make([]string, 0, len(props)+1)
	if withID && !slices.Contains(props, "id") {
		out = append(out, "id")
	}
	for _, p := range props {
		answered := dataType.AnsweredAs(p)
		if answered == nil {
			answered = []string{p}
		}
		for _, name := range answered {
			if !slices.Contains(out, name) && (name == p || !slices.Contains(props, name)) {
				out = append(out, name)
			}
		}
	}
	return out
}

// PickedByServer reports whether a record of dataType asked for props holds
// name only where the server picks it: a field one of props comes back as, one
// of several, as data:asText is where data was asked for. A field asked for by
// its own name comes back whatever the server would pick.
func PickedByServer(dataType *spec.Object, props []string, name string) bool {
	if slices.Contains(props, name) {
		return false
	}
	for _, p := range props {
		if slices.Contains(dataType.AnsweredAs(p), name) {
			return true
		}
	}
	return false
}

// RecordFieldDoc returns the documentation of a field of a record type of
// dataType asked for props, saying where the server picks whether to send it.
func RecordFieldDoc(dataType *spec.Object, props []string, field *spec.Field) string {
	if !PickedByServer(dataType, props, field.Name) {
		return field.Doc
	}
	var others []string
	for _, p := range props {
		answered := dataType.AnsweredAs(p)
		if slices.Contains(answered, field.Name) {
			for _, name := range answered {
				if name != field.Name {
					others = append(others, name)
				}
			}
			break
		}
	}
	return field.Doc + " The server sends this or " + strings.Join(others, " or ") +
		", whichever suits the value, so it may be absent."
}

// SameNarrowing maps each call that narrows what it fetches to the first call
// of the request that narrows it the same way, and a call that is the first to
// itself. A call that narrows nothing is not in the map at all.
//
// Two calls of one request reading the same type through the same method and
// asking for the same properties describe one record, so generating a type for
// each would be two names for one shape, and a caller passing a record from one
// to a function written for the other would have to convert between them. The
// property lists have to agree in order as well as in content, since the order
// is the order the generated fields are written in.
//
// A call asking for a named set is grouped with the calls asking for that set,
// and not with one that happens to list the same properties: the set is the
// name the author chose, and a call that spells the list out has not asked for
// it. The two shapes are the same and the two names are not, which is the
// author's to settle by asking for the set in both places.
func SameNarrowing(calls []*request.Call) map[*request.Call]*request.Call {
	first := make(map[string]*request.Call, len(calls))
	out := make(map[*request.Call]*request.Call, len(calls))
	for _, c := range calls {
		if c.Properties == nil && c.NestedProperties == nil {
			continue
		}
		// The method is part of the key because the response type is the
		// method's, whatever the records inside it are.
		key := strings.Join([]string{
			c.Method.Name,
			c.Method.DataType,
			setName(c.PropertySet),
			propertyList(c.Properties),
			c.Method.NestedType,
			setName(c.NestedPropertySet),
			propertyList(c.NestedProperties),
		}, "\x01")
		if seen, dup := first[key]; dup {
			out[c] = seen
			continue
		}
		first[key] = c
		out[c] = c
	}
	return out
}

// propertyList writes a list of properties into a narrowing key, keeping apart
// the list that is not given, which fetches every property, from the list given
// empty, which fetches none: the id alone of a /get's records, and nothing of
// a body part.
func propertyList(props []string) string {
	if props == nil {
		return "*"
	}
	return "=" + strings.Join(props, "\x00")
}

// setName returns the name of a property set, and an empty string where a call
// asked for none.
func setName(s *request.PropertySet) string {
	if s == nil {
		return ""
	}
	return s.Name
}

// Creation is the name a generated file gives one creation id, so that a
// caller reading back what a /set created spells it once rather than twice.
type Creation struct {
	// Name is the identifier the constant goes by.
	Name string
	// ID is the creation id as the request wrote it.
	ID string
}

// Creations names the creation ids a request invents, keeping the names unique
// among everything else the file declares. Renaming one in the request renames
// the constant with it, which is what turns a rename into a compile error
// rather than a lookup that quietly misses.
func Creations(taken map[string]bool, prefix string, ids []string, name func(string) string) []Creation {
	out := make([]Creation, 0, len(ids))
	for _, id := range ids {
		out = append(out, Creation{Name: Unique(taken, prefix+name(id)), ID: id})
	}
	return out
}

// RequestsDir names the directory the requests at paths were read from, for
// the Source line of a file generated from all of them: the deepest one that
// holds them all, since the requests of one package may sit in several
// directories under the one generation was pointed at.
func RequestsDir(paths []string) string {
	var common []string
	for i, p := range paths {
		dir := strings.Split(path.Dir(strings.ReplaceAll(p, `\`, "/")), "/")
		if i == 0 {
			common = dir
			continue
		}
		n := 0
		for n < len(common) && n < len(dir) && common[n] == dir[n] {
			n++
		}
		common = common[:n]
	}
	if len(common) == 0 {
		return "."
	}
	return strings.Join(common, "/")
}
