// repoRoot is the module root, relative to this package.
const repoRoot = "../../.."

// exampleDir is where the generated Rust is committed, under the example crate.
var exampleDir = filepath.Join(repoRoot, "example", "rust", "src", "jmapq")

// TestGeneratedExampleIsUpToDate checks the committed Rust against what the
// example queries produce now. The Go and TypeScript clients have the same
// test; this one keeps the third language from drifting while the others are
// kept in step.
func TestGeneratedExampleIsUpToDate(t *testing.T) {
	for name, src := range generateExample(t) {
		compare(t, filepath.Join(exampleDir, name), src)
	}
}

// TestGeneratedRustCompiles checks the things about the output that a reader
// would notice and a diff would not. What the compiler says is left to the
// crate under example/rust, which CI builds; these are the mistakes a
// generator makes that would leave the output looking plausible.
func TestGeneratedRustCompiles(t *testing.T) {
	files := generateExample(t)
	for name, src := range files {
		text := string(src)
		if !strings.HasPrefix(text, "// Code generated by jmapc. DO NOT EDIT.") {
			t.Errorf("%s does not say it is generated", name)
		}
		if !strings.HasSuffix(text, "}\n") && !strings.HasSuffix(text, ";\n") {
			t.Errorf("%s does not end where an item ends", name)
		}
		if strings.Contains(text, "\n\n\n") {
			t.Errorf("%s has a run of blank lines rustfmt would take out", name)
		}
		if name == "mod.rs" || name == "types.rs" || name == "client.rs" {
			continue
		}
		if !strings.Contains(text, "pub async fn ") {
			t.Errorf("%s holds no query function", name)
		}
		// Every module names the runtime and builds a request from it; a
		// module that does not is one the generator wrote half of.
		for _, want := range []string{"use super::client::", "let req = Request {", "Result<"} {
			if !strings.Contains(text, want) {
				t.Errorf("%s does not contain %q", name, want)
			}
		}
	}

	// Every module the mod.rs declares has to be there, and every file it
	// wrote has to be declared: a module Rust cannot see is a file that never
	// compiles.
	mod := string(files["mod.rs"])
	for name := range files {
		if name == "mod.rs" {
			continue
		}
		decl := "pub mod " + strings.TrimSuffix(name, ".rs") + ";"
		if !strings.Contains(mod, decl) {
			t.Errorf("mod.rs does not declare %s", name)
		}
	}
	for _, line := range strings.Split(mod, "\n") {
		name, ok := strings.CutPrefix(line, "pub mod ")
		if !ok {
			continue
		}
		if _, written := files[strings.TrimSuffix(name, ";")+".rs"]; !written {
			t.Errorf("mod.rs declares %s, which was not written", name)
		}
	}
}

// generateExample generates the whole of the example client.
func generateExample(t *testing.T) map[string][]byte {
	t.Helper()
	catalogue := spec.Standard()
	files, err := (&QueryGenerator{Spec: catalogue, Queries: parseExample(t)}).Generate()
	if err != nil {
		t.Fatalf("generating the example client: %v", err)
	}
	types, err := (&TypeGenerator{Spec: catalogue, Skip: map[string]bool{"PatchObject": true}}).Generate()
	if err != nil {
		t.Fatalf("generating the types: %v", err)
	}
	client, err := (&ClientGenerator{}).Generate()
	if err != nil {
		t.Fatalf("generating the client: %v", err)
	}
	files["types.rs"] = types
	files["client.rs"] = client
	return files
}

// parseExample parses the example queries.
func parseExample(t *testing.T) []*query.Query {
	t.Helper()
	dir := filepath.Join(repoRoot, "example", "queries")
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("reading %s: %v", dir, err)
	}
	parser := query.NewParser(spec.Standard())
	var out []*query.Query
	for _, e := range entries {
		if !strings.HasSuffix(e.Name(), query.Extension) {
			continue
		}
		q, err := parser.ParseFile(filepath.Join(dir, e.Name()))
		if err != nil {
			t.Fatalf("checking %s:\n%v", e.Name(), err)
		}
		q.Path = filepath.ToSlash(filepath.Join("queries", e.Name()))
		out = append(out, q)
	}
	return out
}

// compare checks a generated file against the one on disk.
func compare(t *testing.T, path string, got []byte) {
	t.Helper()
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("reading %s: %v", path, err)
	}
	if string(got) == string(want) {
		return
	}
	wantLines, gotLines := strings.Split(string(want), "\n"), strings.Split(string(got), "\n")
	for i := 0; i < len(wantLines) && i < len(gotLines); i++ {
		if wantLines[i] != gotLines[i] {
			t.Errorf("%s is out of date; run go generate ./...\nfirst difference at line %d:\n\ton disk:   %s\n\tgenerated: %s",
				path, i+1, wantLines[i], gotLines[i])
			return
		}
	}
	t.Errorf("%s is out of date; run go generate ./...", path)
}

// TestOptionalArgumentIsPutInAfterwards checks the argument a caller may leave
// out. The json! macro states an object as it is written, so the members that
// are always there are stated and the rest are put in afterwards.
func TestOptionalArgumentIsPutInAfterwards(t *testing.T) {
	q, err := query.NewParser(spec.Standard()).Parse("GetChanges"+query.Extension, []byte(`{
	  "methodCalls": [["Email/changes", {"sinceState": "{{sinceState}}", "maxChanges": "{{maxChanges?}}"}, "changes"]]
	}`))
	if err != nil {
		t.Fatalf("checking the query:\n%v", err)
	}
	files, err := (&QueryGenerator{Spec: spec.Standard(), Queries: []*query.Query{q}}).Generate()
	if err != nil {
		t.Fatalf("generating: %v", err)
	}
	src := string(files["get_changes.rs"])
	for _, want := range []string{
		"pub max_changes: Option<u64>,",
		"let mut args = json!({",
		"if let Some(value) = &p.max_changes {",
		`args["maxChanges"] = json!(value);`,
	} {
		if !strings.Contains(src, want) {
			t.Errorf("the generated query does not contain %q:\n%s", want, src)
		}
	}
}

// TestOnlyOptionalArgumentsStartFromAnEmptyObject checks the call whose every
// argument may be left out. The empty object is written on one line, which is
// where rustfmt would put it, and the crate is checked with rustfmt rather
// than formatted by it.
func TestOnlyOptionalArgumentsStartFromAnEmptyObject(t *testing.T) {
	q, err := query.NewParser(spec.Standard()).Parse("EchoMaybe"+query.Extension, []byte(`{
	  "methodCalls": [["Core/echo", {"value": "{{value?}}"}, "c0"]]
	}`))
	if err != nil {
		t.Fatalf("checking the query:\n%v", err)
	}
	files, err := (&QueryGenerator{Spec: spec.Standard(), Queries: []*query.Query{q}}).Generate()
	if err != nil {
		t.Fatalf("generating: %v", err)
	}
	src := string(files["echo_maybe.rs"])
	if !strings.Contains(src, "let mut args = json!({});") {
		t.Errorf("the empty object is not written the way rustfmt writes one:\n%s", src)
	}
}
