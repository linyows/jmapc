// Package ts writes TypeScript from the JMAP data model and the queries
// checked against it. What it produces has no dependencies: the runtime it
// needs is small enough to generate alongside the queries, so a project takes
// on nothing but the files jmapc writes.
package ts

import (
	"bytes"
	"fmt"
	"strconv"
	"strings"

	"github.com/linyows/jmapc/internal/spec"
)

// TypeGenerator writes the TypeScript declarations for the object types in a
// catalogue.
type TypeGenerator struct {
	// Spec is the catalogue to generate from.
	Spec *spec.Spec
	// Skip names object types to leave out.
	Skip map[string]bool
}

// Generate returns the source of types.ts.
func (g *TypeGenerator) Generate() ([]byte, error) {
	var buf bytes.Buffer
	writeHeader(&buf, "the JMAP data model in internal/spec")

	writeComment(&buf, "", "The primitive types that carry a format rather than a shape. Each is a "+
		"string underneath, and named so that the format is visible in a signature and two of them "+
		"cannot be swapped by accident.")
	buf.WriteString("\n")
	for _, alias := range spec.TSPrimitiveAliases() {
		writeComment(&buf, "", alias.Doc)
		fmt.Fprintf(&buf, "export type %s = string\n\n", alias.Name)
	}

	writeComment(&buf, "", "A set of changes to apply to a record, keyed by JSON pointer into it. "+
		"A null value removes what the pointer names.")
	buf.WriteString("export type PatchObject = { [pointer: string]: unknown }\n\n")

	for _, o := range g.Spec.Objects() {
		if g.Skip[o.Name] {
			continue
		}
		g.writeObject(&buf, o)
	}
	return buf.Bytes(), nil
}

// writeObject writes the interface for one object type.
func (g *TypeGenerator) writeObject(buf *bytes.Buffer, o *spec.Object) {
	doc := o.Doc
	if o.Capability != "" && o.Capability != spec.CapabilityCore {
		doc += "\n\nA request using this type must declare " + o.Capability + "."
	}
	writeComment(buf, "", doc)
	fmt.Fprintf(buf, "export interface %s {\n", spec.ExportedName(o.Name))
	for i, f := range o.Fields {
		if i > 0 {
			buf.WriteString("\n")
		}
		g.writeField(buf, o, f)
	}
	buf.WriteString("}\n\n")
}

// writeField writes one member of an interface. Everything a client may leave
// out is optional, which is how TypeScript says what a Go omitzero tag says.
func (g *TypeGenerator) writeField(buf *bytes.Buffer, o *spec.Object, f *spec.Field) {
	doc := f.Doc
	switch {
	case f.ServerSet && o.Kind == spec.KindData:
		doc = strings.TrimSpace(doc + "\n\nThe server sets this property; it may not be set by the client.")
	case f.Immutable && o.Kind == spec.KindData:
		doc = strings.TrimSpace(doc + "\n\nThis property may be set when the record is created, but not changed afterwards.")
	}
	if f.Default != "" {
		doc = strings.TrimSpace(doc + "\n\nThe server assumes " + f.Default + " when this property is omitted.")
	}
	if f.Capability != "" && f.Capability != o.Capability {
		doc = strings.TrimSpace(doc + "\n\nA request using this property must declare " + f.Capability + ".")
	}
	writeComment(buf, "  ", doc)

	name := f.Name
	if spec.TSNeedsQuoting(name) {
		name = strconv.Quote(name)
	}
	optional := ""
	if o.Kind != spec.KindResponse {
		optional = "?"
	}
	fmt.Fprintf(buf, "  %s%s: %s\n", name, optional, f.ParsedType().TSType())
}

// writeHeader writes the banner every generated file carries.
func writeHeader(buf *bytes.Buffer, source string) {
	buf.WriteString("// Code generated by jmapc. DO NOT EDIT.\n")
	fmt.Fprintf(buf, "// Source: %s\n\n", strings.ReplaceAll(source, `\`, "/"))
}
