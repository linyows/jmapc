package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"

	"github.com/linyows/jmapc/internal/spec"
)

// TypeGenerator writes Go declarations for the object types in a catalogue.
// jmapc uses it on itself: the runtime package's JMAP data types are generated
// from the same catalogue the query generator resolves names against, so the
// two can never drift apart.
type TypeGenerator struct {
	// Spec is the catalogue to generate from.
	Spec *spec.Spec
	// Package is the name of the package to generate into.
	Package string
	// Qualifier prefixes references to runtime types, and is empty when
	// generating into the runtime package itself.
	Qualifier string
	// Skip names object types to leave out, for those the runtime package
	// declares by hand.
	Skip map[string]bool
}

// Generate returns the formatted source of the type declarations.
func (g *TypeGenerator) Generate() ([]byte, error) {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by jmapc. DO NOT EDIT.\n")
	fmt.Fprintf(&buf, "// Source: the JMAP data model in internal/spec.\n\n")
	fmt.Fprintf(&buf, "package %s\n", g.Package)
	if g.Qualifier != "" {
		fmt.Fprintf(&buf, "\nimport %q\n", "github.com/linyows/jmapc")
	}

	for _, o := range g.Spec.Objects() {
		if g.Skip[o.Name] {
			continue
		}
		g.writeObject(&buf, o)
	}

	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gen: formatting generated types: %w\n%s", err, buf.String())
	}
	return src, nil
}

// writeObject writes the struct declaration for one object type.
func (g *TypeGenerator) writeObject(buf *bytes.Buffer, o *spec.Object) {
	buf.WriteString("\n")
	doc := o.Doc
	if o.Capability != "" && o.Capability != spec.CapabilityCore {
		doc += "\n\nA request using this type must declare " + o.Capability + "."
	}
	writeComment(buf, "", doc)
	fmt.Fprintf(buf, "type %s struct {\n", spec.ExportedName(o.Name))
	for i, f := range o.Fields {
		if i > 0 {
			buf.WriteString("\n")
		}
		g.writeField(buf, o, f)
	}
	buf.WriteString("}\n")
}

// writeField writes one struct field, with its documentation and JSON tag.
func (g *TypeGenerator) writeField(buf *bytes.Buffer, o *spec.Object, f *spec.Field) {
	doc := f.Doc
	switch {
	case f.ServerSet && o.Kind == spec.KindData:
		doc = strings.TrimSpace(doc + "\n\nThe server sets this property; it may not be set by the client.")
	case f.Immutable && o.Kind == spec.KindData:
		doc = strings.TrimSpace(doc + "\n\nThis property may be set when the record is created, but not changed afterwards.")
	}
	if f.Default != "" {
		doc = strings.TrimSpace(doc + "\n\nThe server assumes " + f.Default + " when this property is omitted.")
	}
	writeComment(buf, "\t", doc)
	fmt.Fprintf(buf, "\t%s %s `json:%q`\n", spec.ExportedName(f.Name), g.fieldType(o, f), g.jsonTag(o, f))
}

// fieldType returns the Go type for a field. A field whose omission means
// something other than its Go zero value is represented as a pointer, so that
// leaving it unset and setting it to the zero value stay distinguishable.
func (g *TypeGenerator) fieldType(o *spec.Object, f *spec.Field) string {
	t := f.ParsedType()
	goType := t.GoType(g.Qualifier)
	if o.Kind != spec.KindResponse && hasNonZeroDefault(f) && !strings.HasPrefix(goType, "*") &&
		!strings.HasPrefix(goType, "[]") && !strings.HasPrefix(goType, "map[") {
		return "*" + goType
	}
	return goType
}

// jsonTag returns the struct tag for a field. Everything the client may send is
// omitted when it holds its zero value, so that a request carries only what the
// query actually set. Response fields are never re-encoded, so they keep their
// name alone.
func (g *TypeGenerator) jsonTag(o *spec.Object, f *spec.Field) string {
	if o.Kind == spec.KindResponse {
		return f.Name
	}
	return f.Name + ",omitzero"
}

// hasNonZeroDefault reports whether the server's default for an omitted field
// differs from the Go zero value, which is what makes the distinction between
// "unset" and "set to zero" observable.
func hasNonZeroDefault(f *spec.Field) bool {
	switch f.Default {
	case "", "false", "0", "null":
		return false
	}
	return true
}
