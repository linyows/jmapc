// TestConfigFile checks that settings are read from jmapc.json in the working
// directory, which is how go:generate invokes the tool.
func TestConfigFile(t *testing.T) {
	dir := workspace(t, map[string]string{
		"jmapc.json":                `{"queries": "q", "out": "client", "package": "mailq"}`,
		"q/ListMailboxes.jmap.json": listMailboxes,
	})
	t.Chdir(dir)

	if err := run([]string{"generate"}); err != nil {
		t.Fatalf("generate: %v", err)
	}
	src, err := os.ReadFile(filepath.Join(dir, "client", "listmailboxes_gen.go"))
	if err != nil {
		t.Fatalf("reading the generated client: %v", err)
	}
	if !strings.HasPrefix(string(src), "// Code generated by jmapc. DO NOT EDIT.") {
		t.Errorf("the generated file does not say it is generated:\n%s", src)
	}
	if !strings.Contains(string(src), "package mailq") {
		t.Errorf("the generated file is not in the configured package:\n%s", src)
	}
}

