const notesSchema = `{
  "capability": "urn:example:params:jmap:notes",
  "types": [
    {
      "name": "Note",
      "doc": "Note is a scrap of text the user keeps.",
      "properties": [
        {"name": "id", "type": "Id", "serverSet": true, "immutable": true, "doc": "The id of the note."},
        {"name": "title", "type": "String", "doc": "The note's title."}
      ],
      "methods": ["get", "query"]
    },
    {
      "name": "NoteFilterCondition",
      "doc": "NoteFilterCondition is a condition a note must satisfy to match a Note/query.",
      "properties": [{"name": "text", "type": "String", "doc": "Matches notes containing this text."}]
    }
  ]
}`

// TestSchemaExtendsTheModel checks that a query against a vendor capability is
// generated, and checked, just as one against a standard type is.
func TestSchemaExtendsTheModel(t *testing.T) {
	dir := workspace(t, map[string]string{
		"schema/notes.json": notesSchema,
		"queries/FindNotes.jmap.json": `{
		  "methodCalls": [
		    ["Note/query", {"filter": {"text": "{{phrase}}"}}, "search"],
		    ["Note/get", {
		      "#ids": {"resultOf": "search", "name": "Note/query", "path": "/ids"},
		      "properties": ["id", "title"]
		    }, "fetch"]
		  ],
		  "_returns": "fetch"
		}`,
	})
	out := filepath.Join(dir, "jmapq")

	err := run([]string{"generate",
		"-schema", filepath.Join(dir, "schema", "notes.json"),
		"-queries", filepath.Join(dir, "queries"),
		"-out", out,
	})
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	src, err := os.ReadFile(filepath.Join(out, "findnotes_gen.go"))
	if err != nil {
		t.Fatalf("reading the generated client: %v", err)
	}
	for _, want := range []string{
		`"urn:example:params:jmap:notes"`,
		"type FindNotesNote struct",
		`Title string ` + "`json:\"title\"`",
	} {
		if !strings.Contains(string(src), want) {
			t.Errorf("the generated client does not contain %q:\n%s", want, src)
		}
	}
}

